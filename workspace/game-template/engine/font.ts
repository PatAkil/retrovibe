function compileGlyph(rows: GlyphRows): Glyph {
  const w = rows[0].length;
  const cells: [number, number][] = [];
  rows.forEach((row, gy) => {
    for (let gx = 0; gx < w; gx++) {
      if (row[gx] === '#') {cells.push([gx, gy]);}
    }
  });
  return { w, cells };
}

const GLYPHS: Readonly<Record<string, Glyph>> = Object.fromEntries(
  Object.entries(FONT_ROWS).map(([ch, rows]) => [ch, compileGlyph(rows)]),
);

export function glyphFor(ch: string): Glyph | undefined {
  return GLYPHS[ch];
}

export function glyphWidth(ch: string): number {
  return glyphFor(ch)?.w ?? GLYPH_W;
}
